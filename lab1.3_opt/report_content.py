"""Компактное содержание дополнительного отчёта по дисперсионному анализу."""

import json

import pandas as pd


def fmt(value, digits=2):
    return f"{float(value):,.{digits}f}".replace(",", " ").replace(".", ",")


def pformat(value):
    return f"{float(value):.3e}".replace(".", ",") if value < .001 else fmt(value, 5)


def blocks_for_report(results):
    summary = json.loads((results / "summary.json").read_text(encoding="utf-8"))
    read = lambda name: pd.read_csv(results / f"{name}.csv")
    desc = read("descriptive_statistics").set_index("group")
    blocks, table_number, figure_number = [], 0, 0

    def h(text, level=1):
        blocks.append({"kind": "heading", "text": text, "level": level})

    def p(text):
        blocks.append({"kind": "paragraph", "text": text})

    def eq(text):
        blocks.append({"kind": "equation", "text": text})

    def table(key, title, headers, rows):
        nonlocal table_number
        table_number += 1
        blocks.append({"kind": "table", "key": key, "caption": f"Таблица {table_number}. {title}",
                       "headers": headers, "rows": rows})

    def figure(file, title):
        nonlocal figure_number
        figure_number += 1
        blocks.append({"kind": "figure", "file": file, "caption": f"Рис. {figure_number} - {title}"})

    h("Цель работы")
    p("Применить два дополнительных метода дисперсионного анализа – ANOVA Уэлча и ANOVA "
      "Брауна–Форсайта – для сравнения средних цен автомобилей с разными типами привода "
      "при неодинаковых дисперсиях. Сопоставить результаты и дать их интерпретацию.")

    h("1 Описание исходных данных")
    p("Использован тот же набор 1985 Auto Imports («Automobile»), что и в основной лабораторной "
      "работе 1.3. Файл imports-85.data содержит 205 записей об автомобилях и 26 признаков. "
      "Для обоих дополнительных методов достаточно двух переменных.")
    p("price – зависимая количественная переменная, цена автомобиля в долларах США. "
      "drive-wheels – независимый категориальный фактор: 4wd – полный привод, fwd – передний, "
      "rwd – задний. Переменная aspiration в этом дополнении не используется. "
      "Интервальное разбиение фактора не требуется: его градации заданы в исходном наборе.")
    quality = read("data_quality")
    table("quality", "Проверка исходных данных",
          ["Признак", "Тип", "Всего", "Заполнено", "Пропуски", "В анализе"],
          [[r.variable, r.type, int(r.total), int(r.valid), int(r.missing), int(r.in_analysis)]
           for r in quality.itertuples()])
    p("Цена отсутствует в строках 10, 45, 46 и 130 исходного файла. Эти четыре записи исключены "
      "без заполнения пропусков. В обоих методах используются одинаковые 201 наблюдение: "
      "4wd – 8, fwd – 118, rwd – 75. Расчёты выполнены в Python с библиотеками NumPy, pandas, "
      "SciPy и statsmodels. Уровень значимости α = 0,05.")

    h("2 Результаты дескриптивного анализа")
    h("2.1 Базовые статистики цены", 2)
    fields = [("Число наблюдений", "count", 0), ("Среднее, долл.", "mean", 2),
              ("Медиана, долл.", "median", 2), ("Минимум, долл.", "minimum", 0),
              ("Максимум, долл.", "maximum", 0), ("Размах, долл.", "range", 0),
              ("Дисперсия, долл.²", "variance", 2),
              ("Стандартное отклонение, долл.", "standard_deviation", 2),
              ("Первый квартиль, долл.", "q1", 2), ("Третий квартиль, долл.", "q3", 2),
              ("Межквартильный размах, долл.", "iqr", 2), ("Асимметрия", "skewness", 3)]
    table("descriptive", "Базовые статистики цены в целом и по типу привода",
          ["Показатель", "Вся выборка", "4wd", "fwd", "rwd"],
          [[label] + [fmt(desc.loc[g, field], digits) for g in ["all", "4wd", "fwd", "rwd"]]
           for label, field, digits in fields])
    p(f"Средняя цена равна {fmt(desc.loc['all', 'mean'])} долл., медиана – "
      f"{fmt(desc.loc['all', 'median'])} долл. Превышение среднего над медианой соответствует "
      "правосторонней асимметрии. Наибольшие выборочные средняя цена и разброс наблюдаются "
      "у rwd. Дисперсии и стандартные отклонения рассчитаны с делителем n − 1. "
      "Эти показатели совпадают с основным отчётом, поскольку отклик и выборка сохранены.")

    h("2.2 Гистограммы цены и формула Стерджесса", 2)
    eq("k = ceil(1 + log₂(n));     h = (max(price) − min(price)) / k")
    p("Число интервалов k округляется вверх; h – длина интервала. Параметры определены "
      "отдельно для всей выборки и каждого привода. Последний интервал включает максимум.")
    bins = read("histogram_bins").drop_duplicates("group")
    table("histograms", "Параметры гистограмм по формуле Стерджесса",
          ["Выборка", "n", "Минимум", "Максимум", "k", "h, долл."],
          [["вся выборка" if r.group == "all" else r.group, int(r.n),
            fmt(desc.loc[r.group, "minimum"], 0), fmt(desc.loc[r.group, "maximum"], 0),
            int(r.k), fmt(r.h)] for r in bins.itertuples()])
    figure("price_histograms.png", "Гистограммы цены с шагом интервала по формуле Стерджесса")
    p("Распределения имеют правые хвосты. Диаграмма размаха показывает различия "
      "положения и разброса групп; высокие цены сохранены как часть исходных данных.")
    figure("price_boxplot.png", "Цена по типу привода: медианы, квартильный разброс и средние")

    h("2.3 Проверка предпосылок", 2)
    p("Критерий Шапиро–Уилка проверяет согласованность распределения цены с нормальным. "
      "Для дисперсионного анализа существенны отдельные группы; вся выборка показана "
      "дополнительно. При p < 0,05 гипотеза нормальности отвергается.")
    normality = read("normality_shapiro")
    table("normality", "Проверка нормальности критерием Шапиро–Уилка",
          ["Выборка", "n", "W", "p-value", "Вывод при α = 0,05"],
          [["вся выборка" if r.group == "all" else r.group, int(r.n), fmt(r.W, 4),
            pformat(r.p_value), "H₀ отвергается" if r.p_value < .05 else "H₀ не отвергается"]
           for r in normality.itertuples()])
    figure("price_qq_by_drive.png", "Q–Q-графики цены по типам привода")
    levene = summary["levene"]
    p("Во всех трёх группах нормальность отвергается. Равенство дисперсий проверено "
      f"критерием Левена с центром в медиане: F(2; 198) = {fmt(levene['F'], 4)}, "
      f"p = {pformat(levene['p_value'])}. Гипотеза равенства дисперсий также отвергается. "
      "Поэтому выбраны методы, допускающие неодинаковые дисперсии. Они не устраняют "
      "ограничения, связанные с асимметрией и малой группой 4wd.")

    h("3 Дисперсионные модели")
    p("Применяются два отсутствующих в основном отчёте варианта однофакторного анализа: "
      "ANOVA Уэлча и ANOVA Брауна–Форсайта. Они проверяют равенство средних цен трёх "
      "независимых групп, допуская разные групповые дисперсии. Оба метода используют "
      "исходную шкалу цены; преобразования и новые признаки не вводятся [3, 4].")
    eq("Yᵢⱼ = μᵢ + εᵢⱼ;     E(εᵢⱼ) = 0;     Var(εᵢⱼ) = σᵢ²")
    p("Здесь i – группа привода, j – автомобиль, μᵢ – средняя цена соответствующей группы. "
      "Независимость записей принята как рабочее предположение; близкие модели одной марки "
      "могут быть похожи. F-приближения предполагают нормальность либо достаточно большие "
      "выборки, поэтому выявленные отклонения от нормальности учитываются при выводах.")
    eq("H₀: μ₄wd = μfwd = μrwd;     H₁: хотя бы одна средняя отличается")
    p("Правило решения общее для обоих методов: если p < 0,05, H₀ отвергается. "
      "Общая проверка не устанавливает значимость каждой отдельной пары групп.")

    h("3.1 Дисперсионный анализ Уэлча", 2)
    p("Метод Уэлча учитывает неодинаковую точность групповых средних: каждой группе "
      "назначается вес wᵢ = nᵢ/sᵢ², где nᵢ – объём группы, sᵢ² – выборочная дисперсия. "
      "Взвешенное среднее и поправка к F-статистике учитывают различия дисперсий и объёмов [3, 4].")
    eq("x̄w = Σwᵢx̄ᵢ / Σwᵢ;     T = Σ[(1 − wᵢ/Σwᵢ)²/(nᵢ − 1)]")
    eq("F_W = [Σwᵢ(x̄ᵢ − x̄w)² / (k − 1)] / [1 + 2(k − 2)T/(k² − 1)]")
    p("В этой работе k = 3; степени свободы равны ν₁ = k − 1 и ν₂ = (k² − 1)/(3T).")
    welch = summary["models"]["welch"]
    table("test", "Результат ANOVA Уэлча", ["F", "ν₁", "ν₂", "p-value"],
          [[fmt(welch["F"], 4), fmt(welch["df1"], 0), fmt(welch["df2"], 4), pformat(welch["p_value"])]])
    p(f"p = {pformat(welch['p_value'])} < 0,05: гипотеза равенства всех средних цен "
      "отвергается. Различия сохраняются при учёте неодинаковых групповых дисперсий.")

    h("3.2 Дисперсионный анализ Брауна–Форсайта", 2)
    p("ANOVA Брауна–Форсайта также сравнивает средние при неодинаковых дисперсиях, "
      "но использует другую поправку к внутригрупповому разбросу. В этом разделе "
      "проверяется равенство средних цен. Числитель F-статистики описывает различия "
      "групповых средних относительно общего среднего x̄ [3, 4].")
    eq("F_BF = Σnᵢ(x̄ᵢ − x̄)² / Σ[(1 − nᵢ/N)sᵢ²];     N = 201")
    p("Использована поправка Мехротры к степеням свободы, реализованная в statsmodels "
      "при use_var='bf'. Поэтому обе степени свободы могут быть дробными [3].")
    bf = summary["models"]["brown_forsythe"]
    table("test", "Результат ANOVA Брауна–Форсайта с поправкой Мехротры", ["F", "ν₁", "ν₂", "p-value"],
          [[fmt(bf["F"], 4), fmt(bf["df1"], 4), fmt(bf["df2"], 4), pformat(bf["p_value"])]])
    p(f"p = {pformat(bf['p_value'])} < 0,05: гипотеза равенства всех средних цен "
      "отвергается. Результат согласуется с ANOVA Уэлча.")

    h("4 Сравнительный анализ и интерпретация результатов")
    p("Оба дополнительных метода приводят к одному выводу: не все средние цены автомобилей "
      "с разными типами привода равны. Значения F и p различаются из-за разных способов учёта "
      "неодинаковых дисперсий. Меньшее p-value само по себе не означает, что метод лучше.")
    p("В выборке средняя цена rwd составляет 19 757,61 долл., 4wd – 10 241,00 долл., "
      "fwd – 9 244,78 долл. У rwd наблюдается наибольшая средняя цена; значимость каждой "
      "пары отдельно не проверялась. Согласие двух методов поддерживает общий вывод "
      "о различиях средних при неодинаковых дисперсиях.")
    p("Выводы ограничены асимметрией распределений, восемью автомобилями в группе 4wd "
      "и наблюдательным характером данных. Анализ описывает связь привода с ценой "
      "и не доказывает причинного влияния: марка и другие характеристики не учитывались.")

    h("Источники", 2)
    for source in [
        "1. Методические указания «Лабораторная работа 1.3. Дисперсионный анализ»: ../lab1.3/ЛР1.3.pdf.",
        "2. 1985 Auto Imports: data/imports-85.data; описание признаков – data/imports-85.names.",
        "3. statsmodels. anova_oneway: ANOVA Уэлча и Брауна–Форсайта. "
        "https://www.statsmodels.org/stable/generated/statsmodels.stats.oneway.anova_oneway.html",
        "4. Dag O., Dolgun A., Konar N. M. onewaytests: An R Package for One-Way Tests "
        "in Independent Groups Designs. The R Journal. 2018. "
        "https://journal.r-project.org/articles/RJ-2018-022/index.html",
    ]:
        p(source)
    return blocks

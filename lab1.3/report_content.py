"""Содержание отчёта по разделу «Содержание отчета» методички ЛР1.3.pdf."""

import json

import pandas as pd


def fmt(value, digits=2):
    if pd.isna(value):
        return "—"
    return f"{float(value):,.{digits}f}".replace(",", " ").replace(".", ",")


def pformat(value):
    return f"{float(value):.3e}".replace(".", ",") if value < 0.001 else fmt(value, 5)


def blocks_for_report(results):
    summary = json.loads((results / "summary.json").read_text(encoding="utf-8"))
    one, kw = summary["one_way"], summary["kruskal"]
    read = lambda name: pd.read_csv(results / f"{name}.csv")
    desc = read("descriptive_statistics").set_index("group")
    cells = read("two_way_cell_statistics")
    two_table = read("two_way_anova").set_index("effect")
    blocks = []
    table_number = figure_number = 0

    def h(text, level=1):
        blocks.append({"kind": "heading", "text": text, "level": level})

    def p(text):
        blocks.append({"kind": "paragraph", "text": text})

    def eq(text):
        blocks.append({"kind": "equation", "text": text})

    def table(key, title, headers, rows):
        nonlocal table_number
        table_number += 1
        blocks.append({"kind": "table", "key": key, "caption": f"Таблица {table_number}. {title}",
                       "headers": headers, "rows": rows})

    def figure(filename, title):
        nonlocal figure_number
        figure_number += 1
        blocks.append({"kind": "figure", "file": filename,
                       "caption": f"Рис. {figure_number} - {title}"})

    h("Цель работы")
    p("Изучить однофакторный дисперсионный анализ и критерий Краскела–Уоллиса на примере "
      "сравнения цен автомобилей с разными типами привода. В дополнительном задании "
      "выполнить классический двухфакторный дисперсионный анализ цены по приводу и наддуву двигателя.")

    h("1 Описание исходных данных")
    p("Использован набор 1985 Auto Imports («Automobile») из лабораторных работ 1.1 и 1.2. "
      "Исходный файл lab1/data/imports-85.data содержит 205 записей об автомобилях и 26 признаков. "
      "Описание данных и дескриптивные показатели рассчитаны заново для выбранной переменной price.")
    p("price — зависимая количественная переменная, цена автомобиля в долларах США. "
      "drive-wheels — независимый категориальный фактор: 4wd — полный, fwd — передний, rwd — задний привод. "
      "aspiration — второй категориальный фактор для дополнительного задания: std — стандартное "
      "исполнение без турбонаддува, turbo — турбонаддув. Этот признак выбран по техническому смыслу "
      "и наличию всех шести сочетаний его категорий с приводом.")
    quality = read("data_quality")
    table("quality", "Проверка исходных данных",
          ["Признак", "Тип", "Всего", "Заполнено", "Пропуски", "В анализе"],
          [[r.variable, "количественный" if r.type == "quantitative" else "номинальный",
            int(r.total_rows), int(r.valid_before), int(r.missing_before), int(r.valid_after)]
           for r in quality.itertuples()])
    excluded = read("excluded_rows")
    p(f"Знак «?» распознаётся как пропуск. В строках {', '.join(str(int(v)) for v in excluded['source_row'])} "
      "отсутствует цена, поэтому эти четыре записи исключены. Цена не заполнялась средним. "
      "Во всех дальнейших расчётах используются одни и те же 201 наблюдение. "
      "Пропуски в неиспользуемых признаках не являются основанием для исключения записей.")
    p("Среда выполнения — Python: pandas и NumPy используются для обработки данных, SciPy — для "
      "статистических критериев, statsmodels — для двухфакторной модели, matplotlib — для графиков. "
      "Уровень значимости всех проверок α = 0,05.")

    h("2 Результаты дескриптивного анализа")
    h("2.1 Базовые статистики цены", 2)
    metrics = [("Число наблюдений", "count", 0), ("Среднее, долл.", "mean", 2),
               ("Медиана, долл.", "median", 2), ("Минимум, долл.", "minimum", 0),
               ("Максимум, долл.", "maximum", 0), ("Размах, долл.", "range", 0),
               ("Дисперсия, долл.²", "variance", 2),
               ("Стандартное отклонение, долл.", "standard_deviation", 2),
               ("Первый квартиль, долл.", "q1", 2), ("Третий квартиль, долл.", "q3", 2),
               ("Межквартильный размах, долл.", "iqr", 2), ("Асимметрия", "skewness", 3)]
    table("descriptive", "Базовые статистики цены в целом и по типу привода",
          ["Показатель", "Вся выборка", "4wd", "fwd", "rwd"],
          [[label] + [fmt(desc.loc[group, field], digits) for group in ["all", "4wd", "fwd", "rwd"]]
           for label, field, digits in metrics])
    p(f"Средняя цена всей выборки равна {fmt(desc.loc['all', 'mean'])} долл., медиана — "
      f"{fmt(desc.loc['all', 'median'])} долл. Среднее выше медианы, распределение имеет "
      "правостороннюю асимметрию. Дисперсия рассчитана с делителем n − 1 и выражена в долларах²; "
      "для интерпретации разброса удобнее стандартное отклонение в долларах. Наибольшая "
      "выборочная средняя цена наблюдается у автомобилей с задним приводом.")
    h("2.2 Гистограммы цены и формула Стерджесса", 2)
    eq("k = ceil(1 + log₂(n));     h = (max(price) − min(price)) / k")
    p("k — число интервалов с округлением вверх, h — шаг интервала. Параметры рассчитаны "
      "отдельно для всей выборки и для каждой группы по приводу. Интервалы замкнуты слева "
      "и открыты справа; последний интервал включает максимальное значение.")
    bins = read("histogram_bins").drop_duplicates("group")
    table("histograms", "Параметры гистограмм по формуле Стерджесса",
          ["Выборка", "n", "Минимум", "Максимум", "k", "h, долл."],
          [["вся выборка" if r.group == "all" else r.group, int(r.n),
            fmt(desc.loc[r.group, "minimum"], 0), fmt(desc.loc[r.group, "maximum"], 0),
            int(r.k), fmt(r.h)] for r in bins.itertuples()])
    figure("price_histograms.png", "Гистограммы цены с шагом интервала по формуле Стерджесса")
    p("Гистограммы показывают правые хвосты распределений. Для номинальных факторов привод "
      "и наддув строятся диаграммы частот, поскольку их категории не образуют числовую шкалу.")
    figure("price_boxplot.png", "Цена по типу привода: медианы, квартильный разброс и средние")

    h("2.3 Оценка согласованности с нормальным распределением", 2)
    p("Гипотезы критерия Шапиро–Уилка: H₀ — данные группы согласуются с нормальным "
      "распределением; H₁ — распределение отличается от нормального. При p < 0,05 H₀ отвергается. "
      "Для ANOVA существенны распределения внутри групп; распределение всей выборки "
      "показано дополнительно для описания данных.")
    normality = read("normality_shapiro")
    table("normality", "Проверка нормальности критерием Шапиро–Уилка",
          ["Выборка", "n", "W", "p-value", "Вывод при α = 0,05"],
          [["вся выборка" if r.group == "all" else r.group, int(r.count), fmt(r.W, 4),
            pformat(r.p_value), "H₀ отвергается" if r.reject_normality else "H₀ не отвергается"]
           for r in normality.itertuples()])
    figure("price_qq_by_drive.png", "Q–Q-графики цены по типам привода")
    p("Во всех трёх группах p < 0,05, поэтому гипотеза нормальности отвергается. "
      "На Q–Q-графиках точки отклоняются от прямой, особенно в хвостах. Классическая ANOVA "
      "выполняется в рамках задания, а её результат сопоставляется с критерием "
      "Краскела–Уоллиса, который не требует нормальности. При интерпретации учитывается "
      "малый объём группы 4wd — 8 наблюдений.")

    h("3 Правила и условия применения изучаемых видов дисперсионного анализа")
    p("Однофакторный дисперсионный анализ Фишера применяется для сравнения средних "
      "количественного признака в нескольких независимых группах. В данной работе цена "
      "является числовой переменной, а тип привода задаёт три готовые категории, поэтому "
      "ANOVA соответствует постановке задачи. Её базовые предположения — независимость "
      "наблюдений, нормальность ошибок внутри групп и гомогенность, то есть равенство "
      "генеральных дисперсий. Равные размеры групп не обязательны.")
    p("Одна запись включается только в одну группу; независимость принимается как рабочее "
      "предположение. Классическая ANOVA выполняется по заданию. Поскольку в разделе 2 "
      "выявлены отклонения от нормальности, её вывод сопоставляется с критерием Краскела–Уоллиса.")
    p("Критерий Краскела–Уоллиса применяется к независимым выборкам числовых или порядковых "
      "наблюдений и не требует нормального распределения. Для приближения статистики H "
      "распределением χ² желательно не менее пяти наблюдений в каждой группе; здесь минимум "
      "равен восьми. В расчёте учитываются совпадающие ранги. При одинаковой форме "
      "распределений результат можно трактовать как различие их положения, в том числе "
      "медиан. Без этого условия вывод относится к различию распределений и рангов.")
    p("Двухфакторный дисперсионный анализ сравнивает средние с учётом двух категориальных "
      "факторов и их взаимодействия. Предположения о независимости, нормальности ошибок "
      "и гомогенности дисперсий сохраняются. Для оценки взаимодействия нужны наблюдения "
      "в сочетаниях уровней обоих факторов и остаточные степени свободы. В данном наборе "
      "все шесть сочетаний привода и наддува представлены, поэтому полная модель оценивается.")

    h("4 Формулировка гипотез")
    p("Для однофакторного анализа цены по типу привода проверяются гипотезы:")
    eq("H₀: μ₄wd = μfwd = μrwd;     H₁: хотя бы одно среднее отличается.")
    p("μ — генеральная средняя цена для соответствующего типа привода. Нулевая гипотеза "
      "отвергается, если p < α = 0,05 или Fнабл > Fкрит. Альтернатива не означает, "
      "что обязательно различаются все пары групп.")
    p("Для критерия Краскела–Уоллиса H₀: распределения цены в трёх группах одинаковы; "
      "H₁: хотя бы одна группа имеет отличающееся распределение. Гипотеза отвергается "
      "при p < 0,05 или Hнабл > χ²крит с двумя степенями свободы.")
    p("Проверяются H₀A — отсутствие различий средних, связанных с приводом; H₀B — отсутствие "
      "дополнительного эффекта наддува после учёта привода; H₀AB — отсутствие взаимодействия. "
      "Соответствующие альтернативы предполагают наличие эффекта. Взаимодействие означает, "
      "что разность средних цен turbo и std зависит от типа привода. При p < 0,05 "
      "соответствующая нулевая гипотеза отвергается.")
    p("Во всех проверках α = 0,05. Если p ≥ 0,05, оснований отвергать нулевую гипотезу "
      "недостаточно; это не является доказательством равенства средних или отсутствия эффекта.")

    h("5 Описание градаций фактора")
    p("Основной фактор drive-wheels имеет три номинальные градации: 4wd — полный, "
      "fwd — передний, rwd — задний привод. В дополнительном задании добавлен фактор "
      "aspiration с двумя градациями: std — без турбонаддува, turbo — турбонаддув. "
      "Оба фактора уже категориальные, поэтому разбиение их значений на числовые интервалы "
      "не требуется. Число наблюдений и доли категорий рассчитаны после удаления пропусков цены.")
    frequency_rows = []
    for variable in ["drive-wheels", "aspiration"]:
        for r in read(f"frequencies_{variable}").itertuples():
            frequency_rows.append([variable, r.level, int(r.count), fmt(r.percent)])
    table("frequencies", "Частоты категориальных факторов",
          ["Фактор", "Категория", "Число автомобилей", "Доля, %"], frequency_rows)
    p("Цены разбиты на три непересекающиеся группы по готовым категориям drive-wheels: "
      "4wd — 8 наблюдений, fwd — 118, rwd — 75. Эти группы вместе включают все 201 наблюдение. "
      "Разбиение фактора на числовые интервалы не требуется. Полные выборки цен по группам "
      "сохранены в results/price_groups.csv.")
    figure("category_frequencies.png", "Распределения типов привода и наддува")

    h("6 Результаты дисперсионного анализа")
    h("6.1 Однофакторный дисперсионный анализ Фишера", 2)
    eq("Q = ΣΣ(yᵢⱼ − ȳ)²;     Q1 = Σ nⱼ(ȳⱼ − ȳ)²;     Q2 = ΣΣ(yᵢⱼ − ȳⱼ)²")
    eq("Q = Q1 + Q2")
    p("Q — общая сумма квадратов, Q1 — межгрупповая, Q2 — внутригрупповая. "
      "ȳ — общая средняя цена, ȳⱼ — средняя цена группы j, nⱼ — размер этой группы. "
      "При N = 201 и k = 3 степени свободы равны k − 1 = 2 между группами, N − k = 198 "
      "внутри групп и N − 1 = 200 в целом.")
    p(f"Получено: Q1 = {fmt(one['Q1'])} долл.²; Q2 = {fmt(one['Q2'])} долл.²; "
      f"Q = {fmt(one['Q_total'])} долл.². Равенство Q = Q1 + Q2 выполнено с точностью вычислений.")
    eq("MSмеж = Q1 / (k − 1);     MSвнутр = Q2 / (N − k);     F = MSмеж / MSвнутр")
    anova = read("one_way_anova")
    labels = {"between": "Межгрупповая (Q1)", "within": "Внутригрупповая (Q2)", "total": "Общая (Q)"}
    table("one_way", "Однофакторная ANOVA цены по типу привода",
          ["Источник", "SS, млн долл.²", "df", "MS, млн долл.²", "F", "p-value"],
          [[labels[r.source], fmt(r.SS / 1e6, 4), int(r.df), fmt(r.MS / 1e6, 4),
            fmt(r.F, 4), pformat(r.p_value) if pd.notna(r.p_value) else "—"] for r in anova.itertuples()])
    p(f"Fнабл = {fmt(one['F'], 4)}, Fкрит(2; 198; 0,95) = {fmt(one['F_critical'], 4)}, "
      f"p = {pformat(one['p_value'])}. Fнабл > Fкрит и p < 0,05, поэтому H₀ о равенстве "
      "всех средних цен отвергается. В выборке выявлены различия средних цен между типами привода.")
    eq("η² = Q1 / Q")
    p(f"η² = {fmt(one['eta_squared'], 4)}. Межгрупповые различия соответствуют "
      f"{fmt(one['eta_squared'] * 100)}% общего разброса цены в исследуемых данных. "
      "Этот показатель характеризует связь цены с приводом и не доказывает причинное влияние.")

    h("6.2 Двухфакторный дисперсионный анализ. Дополнительное задание", 2)
    p("Фактор A — drive-wheels с уровнями 4wd, fwd, rwd; фактор B — aspiration с уровнями "
      "std, turbo. Зависимая переменная — price. Используются все 201 наблюдение. "
      "Все шесть сочетаний факторов присутствуют, однако размеры ячеек различаются.")
    table("cells", "Цена по сочетаниям привода и наддува",
          ["Привод", "Наддув", "n", "Средняя, долл.", "Медиана, долл.", "Ст. откл., долл."],
          [[r.drive, r.aspiration, int(r.count), fmt(r.mean), fmt(r.median), fmt(r.standard_deviation)]
           for r in cells.itertuples()])
    eq("priceᵢⱼₖ = μ + Aᵢ + Bⱼ + (A × B)ᵢⱼ + εᵢⱼₖ")
    p("μ — общий уровень цены, Aᵢ и Bⱼ — эффекты факторов, (A × B)ᵢⱼ — их взаимодействие, "
      "εᵢⱼₖ — ошибка. В Python модель задаётся формулой price ~ C(drive) * C(aspiration), "
      "где drive соответствует drive-wheels. Знак * включает оба главных эффекта и взаимодействие.")
    p("Расчёт выполняется в порядке: сначала привод, затем наддув, затем их взаимодействие. "
      "Так как размеры ячеек неодинаковы, этот порядок фиксируется. Каждый следующий эффект "
      "оценивается по добавленному им уменьшению остаточной суммы квадратов. Модель содержит "
      "6 параметров, остаточные степени свободы равны 201 − 6 = 195. В ячейке 4wd × turbo "
      "всего 2 наблюдения, что ограничивает точность выводов по этой комбинации.")
    labels = {"drive": "Привод A", "aspiration": "Наддув B", "interaction": "Взаимодействие A × B", "residual": "Остаток"}
    table("two_way", "Классическая двухфакторная ANOVA для цены",
          ["Эффект", "SS, млн долл.²", "df", "MS, млн долл.²", "F", "p-value"],
          [[labels[effect], fmt(r.SS / 1e6, 4), int(r.df), fmt(r.MS / 1e6, 4), fmt(r.F, 4),
            pformat(r.p_value) if pd.notna(r.p_value) else "—"] for effect, r in two_table.iterrows()])
    p(f"Привод: F(2; 195) = {fmt(two_table.loc['drive', 'F'], 4)}, "
      f"p = {pformat(two_table.loc['drive', 'p_value'])} < 0,05. H₀A отвергается — "
      "тип привода связан с различиями средней цены.")
    p(f"Наддув после учёта привода: F(1; 195) = {fmt(two_table.loc['aspiration', 'F'], 4)}, "
      f"p = {pformat(two_table.loc['aspiration', 'p_value'])} > 0,05. H₀B не отвергается — "
      "дополнительное различие средних цен по наддуву статистически не подтверждено.")
    p(f"Взаимодействие: F(2; 195) = {fmt(two_table.loc['interaction', 'F'], 4)}, "
      f"p = {pformat(two_table.loc['interaction', 'p_value'])} > 0,05. H₀AB не отвергается — "
      "статистических оснований считать, что различие цен turbo и std зависит от привода, недостаточно. "
      "Неотклонение H₀ не доказывает полного отсутствия эффекта.")
    figure("two_way_interaction.png", "Взаимодействие средних цен по приводу и наддуву")
    p("По горизонтали указан тип привода, по вертикали — средняя цена. Линии соответствуют "
      "std и turbo; рядом с точками приведены размеры ячеек. Линии не полностью параллельны, "
      "однако графическое различие само по себе не доказывает взаимодействия. По F-проверке "
      "взаимодействие при α = 0,05 не подтверждено.")

    h("7 Результаты применения критерия Краскела–Уоллиса")
    p("Для проверки сформулированной в разделе 4 гипотезы все 201 значение цены "
      "ранжируются совместно от меньшей цены к большей; совпадающим ценам присваиваются "
      "средние ранги. Далее рассчитываются суммы и средние ранги по группам.")
    ranks = read("kruskal_ranks")
    table("ranks", "Суммы и средние ранги цены по группам",
          ["Тип привода", "n", "Сумма рангов", "Средний ранг"],
          [[r.group, int(r.count), fmt(r.rank_sum, 1), fmt(r.mean_rank, 3)] for r in ranks.itertuples()])
    eq("H* = [12 / (N(N + 1))] Σ(Rⱼ² / nⱼ) − 3(N + 1)")
    eq("C = 1 − Σ(t³ − t) / (N³ − N);     H = H* / C")
    p("Rⱼ — сумма рангов группы, t — число наблюдений с одной и той же ценой, "
      "C — поправка на совпадающие ранги. При N = 201, k = 3 статистика H "
      "сравнивается с распределением χ² с k − 1 = 2 степенями свободы.")
    table("kruskal", "Критерий Краскела–Уоллиса с поправкой на совпадения",
          ["H*", "C", "H", "df", "χ²крит", "p-value"],
          [[fmt(kw['H_before_tie_correction'], 4), fmt(kw['tie_correction'], 6), fmt(kw['H'], 4),
            kw['df'], fmt(kw['chi2_critical'], 4), pformat(kw['p_value'])]])
    p(f"H = {fmt(kw['H'], 4)} > χ²крит = {fmt(kw['chi2_critical'], 4)}, "
      f"p = {pformat(kw['p_value'])} < 0,05. Нулевая гипотеза отвергается: распределения "
      "цены по типам привода различаются. У rwd наибольший средний ранг, что соответствует "
      "более высоким ценам в этой группе. Критерий проверяет различия распределений; "
      "интерпретация как проверки только медиан требует одинаковой формы распределений.")

    h("8 Интерпретация результатов")
    p("1. Для цены автомобиля выполнен новый дескриптивный анализ. После удаления четырёх "
      "пропусков исследуются 201 наблюдение. Построены гистограммы с интервалами по "
      "формуле Стерджесса, рассчитаны характеристики всей выборки и групп по приводу.")
    p("2. Критерий Шапиро–Уилка и Q–Q-графики показывают отклонения от нормальности во всех "
      "трёх группах. Поэтому результат классической ANOVA интерпретируется с учётом "
      "её предпосылок и сопоставляется с ранговым критерием Краскела–Уоллиса.")
    p(f"3. Однофакторная ANOVA отвергает гипотезу равенства всех средних цен: "
      f"F = {fmt(one['F'], 4)}, p = {pformat(one['p_value'])}. "
      f"η² = {fmt(one['eta_squared'], 4)}: межгрупповые различия составляют "
      f"{fmt(one['eta_squared'] * 100)}% общего разброса цены.")
    p(f"4. Критерий Краскела–Уоллиса также обнаруживает различия распределений: "
      f"H = {fmt(kw['H'], 4)}, p = {pformat(kw['p_value'])}. Средние цены в выборке: "
      f"4wd — {fmt(desc.loc['4wd', 'mean'])} долл., fwd — {fmt(desc.loc['fwd', 'mean'])} долл., "
      f"rwd — {fmt(desc.loc['rwd', 'mean'])} долл. Наибольшая выборочная средняя цена и "
      "наибольший средний ранг наблюдаются у rwd. Общие критерии не устанавливают "
      "значимость каждой отдельной пары групп.")
    p("5. В классической двухфакторной модели привод значим. Дополнительный эффект наддува "
      "после учёта привода и взаимодействие факторов при α = 0,05 не подтверждены. "
      "Выводы ограничены несбалансированными размерами ячеек и малой группой 4wd × turbo.")
    p("6. Полученные результаты описывают связи в историческом наборе Automobile. Они не "
      "доказывают причинного влияния привода или наддува на цену: марки, мощность и класс "
      "автомобилей в анализе не контролировались.")
